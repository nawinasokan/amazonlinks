// ───────────────────────── Helpers ─────────────────────────
export const getProductById = (id) => products.find((p) => p.id === id)

export const getProductsByIds = (ids = []) =>
  ids.map((id) => getProductById(id)).filter(Boolean)

export const getProductsByCategory = (categoryId) =>
  products.filter((p) => p.category === categoryId)

export const getFeaturedProducts = () => products.filter((p) => p.isFeatured)

export const getDealProducts = () => products.filter((p) => p.isDeal)

export const getBrandsByCategory = (categoryId) => [
  ...new Set(getProductsByCategory(categoryId).map((p) => p.brand)),
]

export const productCountByCategory = (categoryId) =>
  getProductsByCategory(categoryId).length

export default products
